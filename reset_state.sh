#!/bin/bash
# ==============================================================
# Shelfa: Reset Book Service State
# ==============================================================
# Usage: ./reset_state.sh
# Description: 서비스 서버의 '이미 책을 들고 있음' 상태를 강제로 초기화합니다.
# ==============================================================

STATE_FILE="/home/user/Shelfa/ros2_ws/realtime_results/book_service_state.json"

echo "=============================================================="
echo "🔄 로봇팔 내부 상태 초기화 진행 중..."

if [ -f "$STATE_FILE" ]; then
  rm "$STATE_FILE"
  echo "✅ 기존 상태 파일을 삭제했습니다. (이제 책을 새로 뽑을 수 있습니다!)"
else
  echo "✅ 상태 파일이 이미 비어있습니다. 초기화가 필요 없습니다."
fi
echo "=============================================================="
